// Freezes the old rooms' price table (stage 5 S6) so refunds still work after the old room code and catalogue are
// deleted (S8). Run once now (and again only if old room prices change before S8):  node scripts/gen-legacy-rooms.mjs
//  - public/js/koala-legacy-rooms.js : prices + the refund rules (plan chapter 4 — the same as koala-house-3d
//    scripts/refund-rehearsal.mjs) used when a child first opens the new house with MOVE on
//  - public/js/koala-core.js          : the LEGACY ids block — ensureKoala keeps these ids in a wallet that has not been
//    refunded yet (moved.room2d missing), even after S8 removes them from the catalogue
// Admin-added room items live in the database, not in these files: the refund prices them from the live catalogue
// (they stay until S9).
import fs from "node:fs";
import vm from "node:vm";

const read = (p) => fs.readFileSync(new URL("../" + p, import.meta.url), "utf8");
const store = new Map();
const win = { localStorage: { getItem: (k) => store.get(k) ?? null, setItem: (k, v) => store.set(k, String(v)), removeItem: (k) => store.delete(k) }, addEventListener() {}, location: { search: "" }, navigator: {}, matchMedia: () => ({ matches: false, addEventListener() {} }) };
win.window = win; win.self = win; win.document = { addEventListener() {}, querySelector: () => null, createElement: () => ({ style: {}, getContext: () => null }), documentElement: { lang: "en" } };
const ctx = vm.createContext(win);
for (const f of ["public/js/koala-core.js", "public/js/koala-house.js"]) vm.runInContext(read(f), ctx, { filename: f });
const C = win.KoalaCore, H = win.KoalaHouse;

const SUB2D = ["books", "desk", "frame", "collage", "toys", "petwear"], SUB3D = ["sink", "fridge", "tools", "shoes"];
const room = {}, sub = {}, asmr = [];
for (const it of C.ITEMS) if (it.kind === "room") room[it.id] = it.unlock && it.unlock.coins ? it.unlock.coins : 0;
for (const s of C.SUB_ITEMS) {
  if (s.kind === "asmr") asmr.push(s.id);
  else if (SUB2D.includes(s.kind) || SUB3D.includes(s.kind)) sub[s.id] = { kind: s.kind, cost: C.SUB_COST[s.id] || 0 };
}
const st = H.starter();
const pick = (table) => Object.fromEntries(Object.entries(table).filter(([, v]) => v && v.p).map(([k, v]) => [k, v.p]));
const house = {
  D: Object.fromEntries(Object.values(H.D).filter((d) => d.price).map((d) => [d.id, d.price])),
  ROOMS: Object.fromEntries(Object.entries(H.ROOMS).filter(([, r]) => r.price).map(([k, r]) => [k, r.price])),
  WALLS: pick(H.WALLS), FLOORS: pick(H.FLOORS), HOUSE_STYLES: pick(H.HOUSE_STYLES), YARD_SIZES: pick(H.YARD_SIZES),
  STARTER: { owned: Object.keys(st.owned), walls: Object.keys(st.walls), floors: Object.keys(st.floors), houseStyles: Object.keys(st.houseStyles), yardSizes: Object.keys(st.yardSizes) },
};
const data = { frozen: new Date().toISOString().slice(0, 10), room, sub, asmr, house, asmrBoxPrice: 60 };

const out = `/* GENERATED by scripts/gen-legacy-rooms.mjs (${data.frozen}) — do not edit by hand.
   Old rooms' frozen prices and the refund rules for moving into the new Koala House (stage 5 S6, plan chapter 4):
   - room2d(k): the 2D room in a child's wallet — each owned room item at its price (free / badge items 0), plus owned
     2D room sub-items and the old 3D house's parent sub-items (sink, fridge, tools, shoes — they sit in the wallet, so
     they are refunded once per wallet here). ASMR toys are not refunded: they move to the new house.
   - houseV2(raw): the old 3D Pop-out house saved on this device (koalaHouse:v2) — each owned id once at its price
     (starter things 0, sold things are no longer owned), built rooms (not the study), bought walls / floors / house
     looks / yard sizes. ASMR boxes are left to the house app (one moves, extra ones are refunded there). No save = 0;
     broken JSON = 0 (the raw text is kept on the device for a support look-up).
   Each result is { total, lines: [{ id, n, why }] }. */
(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.KoalaLegacyRooms = api;
})(typeof self !== "undefined" ? self : this, function () {
  const DATA = ${JSON.stringify(data)};
  function room2d(k, liveItem) {
    const lines = [];
    const owned = (k && k.items && k.items.owned) || {}, subOwned = (k && k.items && k.items.subOwned) || {};
    Object.keys(owned).forEach((id) => {
      if (id in DATA.room) { lines.push({ id, n: DATA.room[id], why: DATA.room[id] ? "room" : "free" }); return; }
      // an admin-added room item (database, not frozen): its live price
      const it = liveItem && liveItem(id);
      if (it && it.kind === "room") lines.push({ id, n: (it.unlock && it.unlock.coins) || 0, why: "room (added)" });
    });
    Object.keys(subOwned).forEach((id) => { const s = DATA.sub[id]; if (s) lines.push({ id, n: s.cost, why: "sub:" + s.kind }); });
    return { total: lines.reduce((a, l) => a + l.n, 0), lines };
  }
  function houseV2(raw) {
    if (raw == null) return { total: 0, lines: [], note: "none" };
    let s; try { s = JSON.parse(raw); } catch (e) { return { total: 0, lines: [], note: "broken" }; }
    if (!s || typeof s !== "object") return { total: 0, lines: [], note: "broken" };
    const H = DATA.house, lines = [], starter = (list, id) => H.STARTER[list].includes(id);
    Object.keys(s.owned || {}).forEach((id) => { if (id === "asmrBox" || starter("owned", id)) return; if (H.D[id]) lines.push({ id, n: H.D[id], why: "item" }); });
    Object.values(s.slots || {}).forEach((sl) => { if (sl && H.ROOMS[sl.type]) lines.push({ id: "room:" + sl.type, n: H.ROOMS[sl.type], why: "room" }); });
    [["walls", "WALLS"], ["floors", "FLOORS"], ["houseStyles", "HOUSE_STYLES"], ["yardSizes", "YARD_SIZES"]].forEach(([rec, table]) => {
      Object.keys(s[rec] || {}).forEach((id) => { if (!starter(rec, id) && H[table][id]) lines.push({ id: rec + ":" + id, n: H[table][id], why: rec }); });
    });
    return { total: lines.reduce((a, l) => a + l.n, 0), lines };
  }
  const isRoomId = (id) => id in DATA.room, isSubId = (id) => id in DATA.sub;

  /* Moving in (S6) — called when a child opens the new house. o = { moveOn, core (KoalaCore), progress, kv (get/set),
     n, account, unlimited (admin: 0 coins, marks and keys the same), now, liveItem (catalogue lookup) }.
     moveOn false (MOVE switch off, or no answer): returns { moving: undefined } and touches nothing — no coins, no marks,
     no device id, no device keys.
     moveOn true:
       - 2D room, once per wallet (moved.room2d): refund key refund:room2d, then the old room items leave the wallet
         (ids kept in moved.room2dItems for 90 days); ASMR toys stay.
       - old 3D Pop-out house on this device (koalaHouse:v2), once per device, to the first child who opens the new house
         here (decision 6): key refund:house-v2:<device id>, mark moved.houseV2[device]. koalaHouse:v2 itself is NOT
         removed or changed (its 3D wardrobe 'worn' stays — decision 5); a device mark koalaHouse:movedTo records who got it.
         Broken JSON: 0 coins, raw text kept as koalaHouse:v2.broken { raw, at, deviceId } (90 days).
     Returns { moving: { deviceId, house?, asmrToys, refunded: [{ key, amount }] }, changed } for bridge.moving. */
  const DEVICE_KEY = "ksm_device_id", MOVED_TO = "koalaHouse:movedTo", OLD = "koalaHouse:v2";
  function move(o) {
    if (!o || !o.moveOn || !o.account) return { moving: undefined, changed: false };
    const C = o.core, k = C.ensureKoala(o.progress), now = o.now != null ? o.now : Date.now(), kv = o.kv;
    let changed = false;
    // a broken old save kept for support is dropped after 90 days
    try { const b = JSON.parse(kv.get(OLD + ".broken") || "null"); if (b && now - (Number(b.at) || 0) > 90 * 86400000 && kv.remove) kv.remove(OLD + ".broken"); } catch (e) { /* */ }
    let dev = kv.get(DEVICE_KEY);
    if (!dev) { dev = "d" + now.toString(36) + Math.random().toString(36).slice(2, 8); kv.set(DEVICE_KEY, dev); }
    if (!k.moved.room2d) {
      const r = room2d(k, o.liveItem);
      C.creditSale(o.progress, r.total, "move:room2d", { key: "refund:room2d", unlimited: !!o.unlimited, now });
      k.moved.room2d = now;
      k.moved.room2dItems = { at: now, ids: r.lines.map((l) => l.id) };
      r.lines.forEach((l) => { delete k.items.owned[l.id]; delete k.items.subOwned[l.id]; });
      Object.keys(k.items.sub).forEach((pid) => { if (isRoomId(pid)) delete k.items.sub[pid]; });
      changed = true;
    }
    let house, mark = null;
    try { mark = JSON.parse(kv.get(MOVED_TO) || "null"); } catch (e) { mark = null; }
    const raw = kv.get(OLD);
    if (!mark && raw != null) {
      const r = houseV2(raw);
      if (!k.moved.houseV2 || typeof k.moved.houseV2 !== "object") k.moved.houseV2 = {};
      C.creditSale(o.progress, r.total, "move:house-v2", { key: "refund:house-v2:" + dev, unlimited: !!o.unlimited, now });
      k.moved.houseV2[dev] = now;
      if (r.note === "broken") kv.set(OLD + ".broken", JSON.stringify({ raw, at: now, deviceId: dev }));
      mark = { at: now, deviceId: dev, account: o.account, n: o.n };
      kv.set(MOVED_TO, JSON.stringify(mark));
      changed = true;
    }
    // the child who got this device's old house also gets its contents (the house app moves the ASMR box once — save.asmr.moved)
    if (mark && raw != null && mark.account === o.account && mark.n === o.n) { try { house = JSON.parse(raw); } catch (e) { house = undefined; } }
    const keys = k.keys || {}, refunded = [];
    Object.keys(keys).forEach((key) => {
      if (key === "refund:room2d") refunded.push({ key: "room2d", amount: Math.max(0, Number(keys[key][0]) || 0) });
      else if (key.indexOf("refund:house-v2:") === 0) refunded.push({ key: key.slice("refund:".length), amount: Math.max(0, Number(keys[key][0]) || 0) });
    });
    const asmrToys = Object.keys(k.items.subOwned).filter((id) => DATA.asmr.includes(id));
    const moving = { deviceId: dev, asmrToys, refunded };
    if (house !== undefined) moving.house = house;
    return { moving, changed };
  }
  return { DATA, room2d, houseV2, move, isRoomId, isSubId, ASMR: DATA.asmr.slice() };
});
`;
fs.writeFileSync(new URL("../public/js/koala-legacy-rooms.js", import.meta.url), out);

// koala-core: the ids an un-refunded wallet keeps (room items + 2D/3D-parent sub-items)
const corePath = new URL("../public/js/koala-core.js", import.meta.url);
let core = fs.readFileSync(corePath, "utf8");
const block = `  /* LEGACY-IDS:begin (generated by scripts/gen-legacy-rooms.mjs — old room ids kept in a wallet until it is refunded) */
  const LEGACY_ROOM_IDS = new Set(${JSON.stringify(Object.keys(room).sort())});
  const LEGACY_SUB_IDS = new Set(${JSON.stringify(Object.keys(sub).sort())});
  /* LEGACY-IDS:end */`;
const re = /  \/\* LEGACY-IDS:begin[\s\S]*?\/\* LEGACY-IDS:end \*\//;
if (re.test(core)) core = core.replace(re, block);
else throw new Error("koala-core.js has no LEGACY-IDS block yet — add the markers first");
fs.writeFileSync(corePath, core);
console.log(`frozen ${data.frozen}: room ${Object.keys(room).length} (priced ${Object.values(room).filter(Boolean).length}), sub ${Object.keys(sub).length}, asmr ${asmr.length}, house items ${Object.keys(house.D).length}, rooms ${Object.keys(house.ROOMS).length}`);
