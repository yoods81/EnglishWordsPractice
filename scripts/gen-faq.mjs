// Builds everything that shows the FAQ from one source, scripts/faq-data.json:
//   public/js/faq-data.js  - window.KOALA_FAQ, read by the in-app Help (js/faq.js)
//   public/faq.html        - the public /faq page (English + Korean, FAQPage JSON-LD)
//   public/about.html      - the "popular questions" block between the FAQ markers
// Items marked "appOnly": true (coin rules) appear in the in-app Help only - they are left out of /faq, About and the FAQ structured data.
// Edit the questions in faq-data.json only, then run `npm run gen:faq` (deploy does it too).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "scripts", "faq-data.json"), "utf8"));
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const both = (o) => `<span class="t-en">${esc(o.en)}</span><span class="t-ko">${esc(o.ko)}</span>`;

writeFileSync(join(root, "public", "js", "faq-data.js"),
  `/* AUTO-GENERATED by scripts/gen-faq.mjs from scripts/faq-data.json - do not edit by hand. */\nwindow.KOALA_FAQ = ${JSON.stringify(data)};\n`);

const isPublic = (it) => !it.appOnly;
const item = (it) => `<details class="faq-item"><summary>${both(it.q)}</summary><p>${both(it.a)}</p></details>`;

// ---- /faq page ----
const page = readFileSync(join(root, "scripts", "faq-page.template.html"), "utf8");
const pubGroups = data.groups.map((g) => ({ ...g, items: g.items.filter(isPublic) })).filter((g) => g.items.length);
const sections = pubGroups.map((g) =>
  `<section class="faq-group" id="${g.id}"><h2>${both(g.title)}</h2>\n${g.items.map(item).join("\n")}\n</section>`).join("\n");
const ld = JSON.stringify({
  "@context": "https://schema.org", "@type": "FAQPage",
  mainEntity: pubGroups.flatMap((g) => g.items).map((it) => ({
    "@type": "Question", name: it.q.en, acceptedAnswer: { "@type": "Answer", text: it.a.en } })),
});
writeFileSync(join(root, "public", "faq.html"),
  page.replace("@@SECTIONS@@", sections).replace("@@LD@@", ld));

// ---- About page: featured questions ----
const aboutPath = join(root, "public", "about.html");
const about = readFileSync(aboutPath, "utf8");
const featured = pubGroups.flatMap((g) => g.items).filter((it) => it.featured).map(item).join("\n");
const re = /<!--FAQ:start-->[\s\S]*?<!--FAQ:end-->/;
if (!re.test(about)) throw new Error("about.html is missing the FAQ markers");
writeFileSync(aboutPath, about.replace(re, `<!--FAQ:start-->\n${featured}\n<!--FAQ:end-->`));
console.log(`FAQ: ${data.groups.flatMap((g) => g.items).length} questions in the app, ${pubGroups.flatMap((g) => g.items).length} public`);
